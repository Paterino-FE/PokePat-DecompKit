using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using TilesetEditor.Core.Text;

namespace TilesetEditor.Core.Events;

public sealed record EventProblem(bool IsError, string Event, string Message);

/// <summary>
/// Generates data/scripts/toolkit_events.pory from the event document. Texts are laid out by
/// <see cref="TextLayout"/> (explicit \n \l \p), so the preview shows exactly what the game shows.
/// </summary>
public static partial class PoryscriptGenerator
{
    public const string HashMarker = "// toolkit-hash: ";

    [GeneratedRegex("^[A-Za-z_][A-Za-z0-9_]*$")]
    private static partial Regex LabelRegex();

    public static string Generate(ToolkitEventDocument doc, GbaFont font, Charmap? charmap)
    {
        var body = new StringBuilder();
        var topLevel = new StringBuilder();
        foreach (var e in doc.Events.OrderBy(e => e.Map, StringComparer.Ordinal).ThenBy(e => e.Label, StringComparer.Ordinal))
        {
            body.Append($"// {e.Map}: {OneLine(e.Title)} ({e.Trigger})\n");
            body.Append($"script {e.Label} {{\n");
            bool person = e.Trigger == EventTrigger.Person;
            body.Append(person ? "    lock\n    faceplayer\n" : "    lockall\n");
            _context = (e.Label, 0, topLevel);
            WriteSteps(body, e.Steps, 1, font, charmap);
            body.Append("    closemessage\n");
            body.Append(person ? "    release\n" : "    releaseall\n");
            // Poryscript ends top-level scripts with "return"; an explicit "end" is the pret convention.
            body.Append("    end\n}\n\n");
        }
        body.Append(topLevel);
        var b = body.ToString();
        var header = new StringBuilder();
        header.Append("// AUTO-GENERATED by PokePat DecompKit (Dialogs & Events) – do not edit by hand.\n");
        header.Append("// Source: data/scripts/toolkit_events.json. Make changes in the toolkit.\n");
        header.Append(HashMarker).Append(Hash(b)).Append('\n').Append('\n');
        return header + b;
    }

    public static string Hash(string body) => Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(body.Replace("\r\n", "\n"))))[..16];

    /// <summary>True if the file still is exactly what the toolkit generated (no hand edits).</summary>
    public static bool IsUnmodified(string poryText)
    {
        poryText = poryText.Replace("\r\n", "\n");
        int at = poryText.IndexOf(HashMarker, StringComparison.Ordinal);
        if (at < 0) return false;
        int eol = poryText.IndexOf('\n', at);
        if (eol < 0) return false;
        var hash = poryText[(at + HashMarker.Length)..eol].Trim();
        var body = poryText[(eol + 1)..];
        if (body.StartsWith('\n')) body = body[1..];
        return Hash(body) == hash;
    }

    private static void WriteSteps(StringBuilder sb, List<EventStep> steps, int depth, GbaFont font, Charmap? charmap)
    {
        var ind = new string(' ', depth * 4);
        foreach (var step in steps)
        {
            switch (step)
            {
                case MessageStep m:
                    sb.Append($"{ind}msgbox(\"{TextLayout.Format(m.Text, font, charmap).Encoded}\", MSGBOX_DEFAULT)\n");
                    break;
                case YesNoStep y:
                    sb.Append($"{ind}msgbox(\"{TextLayout.Format(y.Question, font, charmap).Encoded}\", MSGBOX_YESNO)\n");
                    WriteBranch(sb, ind, "var(VAR_RESULT) == YES", "var(VAR_RESULT) == NO", y.Yes, y.No, depth, font, charmap);
                    break;
                case IfFlagStep f:
                    WriteBranch(sb, ind, $"flag({f.Flag})", $"!flag({f.Flag})", f.Then, f.Else, depth, font, charmap);
                    break;
                case SetFlagStep s:
                    sb.Append($"{ind}setflag({s.Flag})\n");
                    break;
                case ClearFlagStep c:
                    sb.Append($"{ind}clearflag({c.Flag})\n");
                    break;
                case GiveItemStep g:
                    sb.Append($"{ind}giveitem({g.Item}, {g.Count})\n");
                    break;
                case CommandStep c when c.Def is { } def:
                    var args = LaidOutArgs(c, def, font, charmap);
                    if (def.TopLevel != null)
                    {
                        var values = new Dictionary<string, string>(c.Args) { ["__name"] = $"{_context.Label}_{def.Id switch { "mart" => "Mart", _ => "Data" }}{_context.Counter++}" };
                        args = new BlockArgs(def, values);
                        _context.TopLevel.Append(def.TopLevel(args)).Append('\n');
                    }
                    foreach (var line in def.Lines(args)) sb.Append(ind).Append(line).Append('\n');
                    if (def.Condition is { } cond)
                    {
                        var (yes, no) = cond(args);
                        WriteBranch(sb, ind, yes, no, c.Then, c.Else, depth, font, charmap);
                    }
                    if (def.IsSwitch)
                    {
                        var cases = c.CaseBranches().Where(x => x.Steps.Count > 0).ToList();
                        if (cases.Count > 0)
                        {
                            sb.Append($"{ind}switch (var(VAR_RESULT)) {{\n");
                            foreach (var (value, _, caseSteps) in cases)
                            {
                                sb.Append($"{ind}    case {value}:\n");
                                WriteSteps(sb, caseSteps, depth + 2, font, charmap);
                            }
                            sb.Append($"{ind}}}\n");
                        }
                    }
                    break;
            }
        }
    }

    [ThreadStatic] private static (string Label, int Counter, StringBuilder TopLevel) _context;

    /// <summary>Block arguments with in-game texts laid out (\n, \l, \p) for the generated script.</summary>
    private static BlockArgs LaidOutArgs(CommandStep c, BlockDef def, GbaFont font, Charmap? charmap)
    {
        var values = new Dictionary<string, string>(c.Args);
        foreach (var p in def.Params.Where(p => p.Kind == ParamKind.Message))
            values[p.Key] = TextLayout.Format(new BlockArgs(def, c.Args)[p.Key], font, charmap).Encoded;
        return new BlockArgs(def, values);
    }

    private static void WriteBranch(StringBuilder sb, string ind, string cond, string negated, List<EventStep> a, List<EventStep> b,
        int depth, GbaFont font, Charmap? charmap)
    {
        if (a.Count == 0 && b.Count == 0) return;
        if (a.Count == 0)
        {
            sb.Append($"{ind}if ({negated}) {{\n");
            WriteSteps(sb, b, depth + 1, font, charmap);
            sb.Append($"{ind}}}\n");
            return;
        }
        sb.Append($"{ind}if ({cond}) {{\n");
        WriteSteps(sb, a, depth + 1, font, charmap);
        if (b.Count > 0)
        {
            sb.Append($"{ind}}} else {{\n");
            WriteSteps(sb, b, depth + 1, font, charmap);
        }
        sb.Append($"{ind}}}\n");
    }

    private static string OneLine(string s) => s.Replace('\n', ' ').Replace('\r', ' ');

    /// <summary>Checks the document before generating: labels, flags, items, texts.</summary>
    public static List<EventProblem> Validate(ToolkitEventDocument doc, GbaFont font, Charmap? charmap, ProjectSymbols? symbols,
        IReadOnlySet<string>? existingLabels = null)
    {
        var problems = new List<EventProblem>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var e in doc.Events)
        {
            string who = e.Title.Length > 0 ? e.Title : e.Label;
            if (!LabelRegex().IsMatch(e.Label)) problems.Add(new(true, who, $"Invalid script name \"{e.Label}\" (letters, digits and _ only)."));
            if (!seen.Add(e.Label)) problems.Add(new(true, who, $"The script name {e.Label} is used more than once."));
            if (existingLabels != null && existingLabels.Contains(e.Label))
                problems.Add(new(true, who, $"The script name {e.Label} already exists in the project's map scripts."));
            if (e.Steps.Count == 0) problems.Add(new(false, who, "The event has no blocks yet."));
            ValidateSteps(e.Steps, who, font, charmap, symbols, problems);
        }
        return problems;
    }

    private static void ValidateSteps(List<EventStep> steps, string who, GbaFont font, Charmap? charmap, ProjectSymbols? symbols, List<EventProblem> problems)
    {
        foreach (var s in steps)
        {
            switch (s)
            {
                case MessageStep m:
                    foreach (var p in TextLayout.Format(m.Text, font, charmap).Problems) problems.Add(new(p.IsError, who, $"Message \"{m.Summary}\": {p.Message}"));
                    break;
                case YesNoStep y:
                    foreach (var p in TextLayout.Format(y.Question, font, charmap).Problems) problems.Add(new(p.IsError, who, $"Question \"{y.Summary}\": {p.Message}"));
                    break;
                case IfFlagStep f: CheckFlag(f.Flag); break;
                case SetFlagStep f: CheckFlag(f.Flag); break;
                case ClearFlagStep f: CheckFlag(f.Flag); break;
                case GiveItemStep g:
                    if (symbols != null && !symbols.IsItem(g.Item)) problems.Add(new(true, who, $"Item {g.Item} does not exist in the project."));
                    if (g.Count is < 1 or > 999) problems.Add(new(true, who, $"Count {g.Count} for {g.Item} must be between 1 and 999."));
                    break;
                case CommandStep c:
                    ValidateCommand(c, who, font, charmap, symbols, problems);
                    break;
            }
            foreach (var (_, branch) in s.Branches()) ValidateSteps(branch, who, font, charmap, symbols, problems);
        }

        void CheckFlag(string flag)
        {
            if (flag.Length == 0) problems.Add(new(true, who, "No flag selected."));
            else if (symbols != null && !symbols.IsFlag(flag)) problems.Add(new(true, who, $"Flag {flag} does not exist in the project (include/constants/flags.h)."));
        }
    }

    private static void ValidateCommand(CommandStep c, string who, GbaFont font, Charmap? charmap, ProjectSymbols? symbols, List<EventProblem> problems)
    {
        if (c.Def is not { } def) { problems.Add(new(true, who, $"Unknown block \"{c.Block}\".")); return; }
        var a = new BlockArgs(def, c.Args);
        string block = def.Title;
        foreach (var p in def.Params)
        {
            var v = a[p.Key];
            if (v.Length == 0)
            {
                if (!p.Optional) problems.Add(new(true, who, $"{block}: \"{p.Label}\" is empty."));
                continue;
            }
            bool IsNumber(string s) => long.TryParse(s, out _) || (s.StartsWith("0x", StringComparison.OrdinalIgnoreCase) && s.Length > 2);
            void Known(IReadOnlyList<string>? list, string what)
            {
                if (symbols == null || list == null || list.Count == 0 || IsNumber(v)) return;
                if (!list.Contains(v)) problems.Add(new(true, who, $"{block}: {what} \"{v}\" does not exist in the project."));
            }
            switch (p.Kind)
            {
                case ParamKind.Message:
                    foreach (var tp in TextLayout.Format(v, font, charmap).Problems) problems.Add(new(tp.IsError, who, $"{block} – {p.Label}: {tp.Message}"));
                    break;
                case ParamKind.Number:
                    if (!IsNumber(v) && !System.Text.RegularExpressions.Regex.IsMatch(v, "^[A-Z_][A-Z0-9_]*$"))
                        problems.Add(new(true, who, $"{block}: \"{p.Label}\" must be a number (is \"{v}\")."));
                    break;
                case ParamKind.Flag: if (symbols != null && !symbols.IsFlag(v) && !IsNumber(v)) problems.Add(new(true, who, $"{block}: flag \"{v}\" does not exist in the project.")); break;
                case ParamKind.Item: Known(symbols?.Items.Select(i => i.Name).ToList(), "Item"); break;
                case ParamKind.Var: Known(symbols?.Vars, "Variable"); break;
                case ParamKind.Species: Known(symbols?.Species, "Pokémon"); break;
                case ParamKind.Trainer: Known(symbols?.Trainers, "Trainer"); break;
                case ParamKind.Map: Known(symbols?.Maps, "Map"); break;
                case ParamKind.Music: Known(symbols?.Music, "Music"); break;
                case ParamKind.Sound: Known(symbols?.Sounds, "Sound"); break;
                case ParamKind.Weather: Known(symbols?.Weathers, "Weather"); break;
                case ParamKind.Special: Known(symbols?.Specials, "Special"); break;
                case ParamKind.Choice:
                    if (p.Choices != null && !p.Choices.Contains(v)) problems.Add(new(true, who, $"{block}: \"{v}\" is not allowed for \"{p.Label}\"."));
                    break;
                case ParamKind.Movement:
                    var moves = BlockCatalog.ParseMovement(v);
                    if (moves.Count == 0) problems.Add(new(true, who, $"{block}: no steps given."));
                    foreach (var (action, count) in moves)
                    {
                        if (symbols is { MovementActions.Count: > 0 } && !symbols.MovementActions.Contains(action))
                            problems.Add(new(true, who, $"{block}: step \"{action}\" does not exist (asm/macros/movement.inc)."));
                        if (count is < 1 or > 99) problems.Add(new(true, who, $"{block}: repeat count {count} for \"{action}\" must be 1–99."));
                    }
                    break;
                case ParamKind.Text when def.Id == "menu" && p.Key == "options":
                    var opts = BlockCatalog.Options(v);
                    if (opts.Count < 2) problems.Add(new(true, who, $"{block}: enter at least two answers (one per line)."));
                    foreach (var o in opts)
                    {
                        var fo = TextLayout.Format(o, font, charmap);
                        foreach (var tp in fo.Problems.Where(x => x.IsError)) problems.Add(new(true, who, $"{block} – answer \"{o}\": {tp.Message}"));
                        if (fo.Boxes[0].Count > 1) problems.Add(new(true, who, $"{block}: answer \"{o}\" is too long for a menu."));
                    }
                    break;
                case ParamKind.Text when def.Id == "move_together" && p.Key == "group":
                    var group = BlockCatalog.Group(v);
                    if (group.Count == 0) problems.Add(new(true, who, $"{block}: enter at least one line \"who: steps\"."));
                    foreach (var (target, steps) in group)
                    {
                        if (target.Length == 0) { problems.Add(new(true, who, $"{block}: \"{steps}\" – put the person first, e.g. \"1: {steps}\".")); continue; }
                        if (!System.Text.RegularExpressions.Regex.IsMatch(target, @"^(OBJ_EVENT_ID_\w+|LOCALID_\w+|\d+|VAR_\w+)$"))
                            problems.Add(new(true, who, $"{block}: \"{target}\" is not a person (OBJ_EVENT_ID_PLAYER, number or LOCALID_…)."));
                        var gm = BlockCatalog.ParseMovement(steps);
                        if (gm.Count == 0) problems.Add(new(true, who, $"{block}: no steps for {target}."));
                        foreach (var (action, count) in gm)
                        {
                            if (symbols is { MovementActions.Count: > 0 } && !symbols.MovementActions.Contains(action))
                                problems.Add(new(true, who, $"{block}: step \"{action}\" does not exist (asm/macros/movement.inc)."));
                            if (count is < 1 or > 99) problems.Add(new(true, who, $"{block}: repeat count {count} for \"{action}\" must be 1–99."));
                        }
                    }
                    if (group.Select(g => g.Target).Distinct().Count() < group.Count)
                        problems.Add(new(true, who, $"{block}: each person may appear only once – put all their steps on one line."));
                    break;
                case ParamKind.Text when def.Id == "mart" && p.Key == "items":
                    var items = BlockCatalog.ItemList(v);
                    if (items.Count == 0) problems.Add(new(true, who, $"{block}: no items given."));
                    if (symbols != null) foreach (var it in items.Where(i => !symbols.IsItem(i))) problems.Add(new(true, who, $"{block}: item \"{it}\" does not exist in the project."));
                    break;
                case ParamKind.Macro:
                    if (symbols is { Macros.Count: > 0 } && symbols.Macros.FirstOrDefault(m => m.Name == v) is not { } macro)
                        problems.Add(new(true, who, $"{block}: command \"{v}\" does not exist in asm/macros/event.inc."));
                    else if (symbols?.Macros.FirstOrDefault(m => m.Name == v) is { } mac)
                        for (int i = 0; i < mac.Params.Count; i++)
                            if (mac.Params[i].Required && a.Raw($"arg{i}").Trim().Length == 0)
                                problems.Add(new(true, who, $"{block} {v}: parameter \"{mac.Params[i].Name}\" is required."));
                    break;
            }
        }
    }

    /// <summary>Builds a label like Route101_TK_OldMan from map and title.</summary>
    public static string SuggestLabel(string map, string title, IEnumerable<string> taken)
    {
        var words = Regex.Split(title.Replace("ä", "ae").Replace("ö", "oe").Replace("ü", "ue").Replace("Ä", "Ae").Replace("Ö", "Oe").Replace("Ü", "Ue").Replace("ß", "ss"),
            "[^A-Za-z0-9]+").Where(w => w.Length > 0);
        var name = string.Concat(words.Select(w => char.ToUpperInvariant(w[0]) + w[1..]));
        if (name.Length == 0) name = "Event";
        var baseLabel = $"{map}_TK_{name}";
        var set = new HashSet<string>(taken, StringComparer.Ordinal);
        var label = baseLabel;
        for (int i = 2; set.Contains(label); i++) label = baseLabel + i;
        return label;
    }
